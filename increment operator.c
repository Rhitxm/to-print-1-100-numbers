// i++ : pre increment operator
#include <stdio.h>

int main() {
    int i=1;
    printf("%d\n", i++);
    printf("%d\n", i);
    return 0;
}
//output:1
       //2
//++i : post increment operator
#include <stdio.h>

int main() {
    int i=1;
    printf("%d\n", ++i);
    printf("%d\n", i);
    return 0;
}
//output:2
       //2
